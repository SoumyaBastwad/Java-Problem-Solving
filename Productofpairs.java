package Demo;
import java.util.Scanner;
public class Productofpairs {

	public static void main(String[] args) {
			    Scanner	sc=new Scanner(System.in);
		           int a=sc.nextInt();
		           int b=sc.nextInt();
		           int c=sc.nextInt();
		           int prod1=a*b;
		           int prod2=a*c;
		           int prod3=b*c;
		           System.out.println(prod1);
		           System.out.println(prod2);
		           System.out.println(prod3);

	}

}

